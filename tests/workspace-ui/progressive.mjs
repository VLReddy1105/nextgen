import assert from "node:assert/strict";
import { chromium } from "../../work/ui-test/node_modules/playwright/index.mjs";
const browser = await chromium.launch({ headless: true, channel: "msedge" });
try {
  const page = await browser.newPage();
  const errors = [];
  page.on("pageerror", e => errors.push(e.message));
  await page.goto("http://127.0.0.1:4173/performance.html?progressive");
  const click = name => page.getByRole("button", { name, exact: true }).click();
  await click("Profile ready");
  await page.getByText("Your next chapter starts with you.").waitFor();
  assert.equal(await page.getByText("No applications yet", { exact: true }).count(), 0);
  assert.ok(await page.getByText("Loading this section…", { exact: true }).count());
  await click("Open projects");
  await page.getByLabel("Loading workspace").waitFor();
  await click("Projects ready");
  await page.locator("main h1").waitFor();
  assert.equal(await page.getByLabel("Loading workspace").count(), 0, "Projects render while mentorship remains pending");
  assert.equal(await page.locator("html").getAttribute("data-calls"), "1");
  await click("Stream complete");
  await click("Open notifications");
  await page.getByText("Loading notifications…", { exact: true }).waitFor();
  assert.equal(await page.getByText("You’re all caught up.", { exact: true }).count(), 0);
  await click("Resolve notices");
  await page.getByRole("button", { name: "Mark all read", exact: true }).waitFor();
  assert.equal(await page.locator("html").getAttribute("data-notice-calls"), "1");
  await page.goto("http://127.0.0.1:4173/performance.html?progressive");
  await click("Profile ready");
  await click("Open detail A");
  await page.waitForFunction(() => Number(document.documentElement.dataset.detailCalls) >= 1);
  const initialDetailCalls = Number(await page.locator("html").getAttribute("data-detail-calls"));
  assert.equal(await page.getByLabel("Loading workspace").count(), 0, "A detail starts without waiting for its catalog");
  await click("Open detail B");
  await page.waitForFunction(before => Number(document.documentElement.dataset.detailCalls) > before, initialDetailCalls);
  assert.equal(await page.locator("html").getAttribute("data-detail-aborted"), "true");
  await click("Resolve detail B");
  await page.getByText("Project B", { exact: true }).first().waitFor();
  const settledCalls = await page.locator("html").getAttribute("data-detail-calls");
  await click("Projects ready");
  assert.equal(await page.locator("html").getAttribute("data-detail-calls"), settledCalls, "Initial supplementary catalog must not restart the active detail");
  await click("Resolve detail A");
  assert.equal(await page.getByText("Project A", { exact: true }).count(), 0, "Late A cannot replace B");
  await click("Open detail A");
  assert.equal(await page.getByText("Project B", { exact: true }).count(), 0, "Previous item is hidden while a different item loads");
  assert.equal(await page.locator("html").getAttribute("data-calls"), "1", "Detail navigation does not reload the workspace");
  assert.deepEqual(errors, []);
  for (const [kind, view] of [["projects", "tasks"], ["projects", "team"], ["communities", "feed"], ["communities", "posts"]]) {
    await page.goto(`http://127.0.0.1:4173/?role=student&page=${kind}&view=${view}`);
    await page.waitForFunction(() => document.documentElement.dataset.activityCalls === "1");
    assert.equal(await page.locator("html").getAttribute("data-activity-calls"), "1", "Activity uses one focused endpoint instead of per-space details");
  }
  console.log("PASS progressive readiness, lazy notifications, independent detail loading, cancellation, and rapid-item isolation");
} finally { await browser.close(); }
